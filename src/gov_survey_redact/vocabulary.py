"""Australian public-sector, Commonwealth/State machinery, and corporate vocabulary.

Every list is built through :func:`alt` so it is always a self-contained
non-capturing group ``(?:...)`` when interpolated into larger regular expressions.
"""

from __future__ import annotations


def alt(*parts: str) -> str:
    """Return a grouped alternation safe to interpolate into any pattern."""
    return "(?:" + "|".join(parts) + ")"


